'use strict';
const fs = require('fs');
const vm = require('vm');
const path = require('path');
const appRoot = path.join(__dirname, '..', 'app', 'src', 'main', 'assets');
const html = fs.readFileSync(path.join(appRoot, 'index.html'), 'utf8');
const data = JSON.parse(fs.readFileSync(path.join(appRoot, 'data.json'), 'utf8'));
const start = html.indexOf('function rate(size)');
const end = html.indexOf('function canonicalEmployeeName', start);
if (start < 0 || end < 0) throw new Error('Cannot find wage helper section in index.html');
const helperSource = html.slice(start, end);
const ctx = { D: { catalog: data.catalog, rates: data.rates } };
vm.createContext(ctx);
vm.runInContext(helperSource, ctx, { filename: 'wage-helpers.js' });
const assert = (condition, message) => { if (!condition) throw new Error(message); };
const normalize = value => String(value || '').normalize('NFD').replace(/[\u0300-\u036f]/g, '').replace(/đ/g, 'd').toLowerCase().replace(/\s+/g, ' ').trim();
const c7Index = data.catalog.findIndex(p => normalize(p.name).includes('cam tu mai') && String(p.size).replace(/\s/g, '').toUpperCase() === 'C7');
const c9Index = data.catalog.findIndex(p => normalize(p.name).includes('cam tu mai') && String(p.size).replace(/\s/g, '').toUpperCase() === 'C9');
const otherC7Index = data.catalog.findIndex(p => !normalize(p.name).includes('cam tu mai') && String(p.size).replace(/\s/g, '').toUpperCase() === 'C7');
if (c7Index < 0 || c9Index < 0 || otherC7Index < 0) throw new Error('Required Cẩm tú mai C7/C9 or non-target C7 source catalog row missing');
const item = (plantIndex, plantName, size, qty) => ({ plantIndex, plantName, size, qty });
const c7_5 = [item(c7Index, data.catalog[c7Index].name, 'C7', 5)];
const c7_2plus3 = [item(c7Index, data.catalog[c7Index].name, 'C7', 2), item(c7Index, data.catalog[c7Index].name, 'C7', 3)];
const c7_4 = [item(c7Index, data.catalog[c7Index].name, 'C7', 4)];
const c9_4 = [item(c9Index, data.catalog[c9Index].name, 'C9', 4)];
const c9_3 = [item(c9Index, data.catalog[c9Index].name, 'C9', 3)];
const c7_name_suffix = [item(c7Index, 'Cẩm tú mai C7', '', 5)];
const baselineC7 = ctx.rate('C7');
const baselineC9 = ctx.rate('C9');
assert(baselineC7 === 2000, `Source data expected C7 baseline 2000, found ${baselineC7}`);
assert(baselineC9 === 3000, `Source data expected C9 baseline 3000, found ${baselineC9}`);
assert(ctx.orderItemRate(c7_5[0], c7_5) === 1600, 'C7 threshold >=5 must be 1600 VND/plant');
assert(c7_2plus3.every(x => ctx.orderItemRate(x, c7_2plus3) === 1600), 'same C7 plant split across multiple lines must aggregate within one order');
assert(ctx.orderItemRate(c7_4[0], c7_4) === baselineC7, 'C7 below threshold must use configured size rate');
assert(ctx.orderItemRate(c9_4[0], c9_4) === 2500, 'C9 threshold >=4 must be 2500 VND/plant');
assert(ctx.orderItemRate(c9_3[0], c9_3) === baselineC9, 'C9 below threshold must use configured size rate');
assert(ctx.orderItemRate(c7_name_suffix[0], c7_name_suffix) === 1600, 'size embedded in plant name must still match C7 exception');
assert(ctx.orderItemRate(item(otherC7Index, data.catalog[otherC7Index].name, 'C7', 10), [item(otherC7Index, data.catalog[otherC7Index].name, 'C7', 10)]) === baselineC7, 'exception must not affect other plant names');
const taoThaiC9 = item(24, 'Táo thái', 'C9', 1);
assert(ctx.orderItemRate(taoThaiC9, [taoThaiC9]) === 5000, 'Táo Thái C9 must use the special 5000 VND/plant rate');
const taoThaiC7 = item(24, 'Táo thái', 'C7', 1);
assert(ctx.orderItemRate(taoThaiC7, [taoThaiC7]) === baselineC7, 'Táo Thái C7 must not inherit the C9-only rate and should use the configured C7 rate');
const otherC9 = item(otherC7Index, data.catalog[otherC7Index].name, 'C9', 1);
assert(ctx.orderItemRate(otherC9, [otherC9]) === baselineC9, 'The Táo Thái override must not affect other C9 plants');
const fixedItem = { plantIndex: c7Index, plantName: 'Cẩm tú mai', size: 'C7', qty: 5, assignedRate: 1750 };
assert(ctx.orderItemRate(fixedItem, [fixedItem]) === 1750, 'Admin-assigned per-item wage snapshot must be honored after assignment');
console.log('Packing wage rule tests passed: source rate table, C7>=5, C9>=4, thresholds, aggregation, name/size matching, Táo Thái C9 at 5000 VND, and non-target plants.');
