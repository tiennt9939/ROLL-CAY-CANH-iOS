const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const h = fs.readFileSync(path.join(__dirname, '../app/src/main/assets/index.html'), 'utf8');
const gradle = fs.readFileSync(path.join(__dirname, '../app/build.gradle.kts'), 'utf8');
assert(gradle.includes('versionCode = 144') && gradle.includes('versionName = "26.2.92"'), 'Android version must match V26.2.92');
assert(h.includes('const candidateChoices=!lines.length&&candidates.length?'), 'ambiguous catalog rows must offer direct candidate buttons');
assert(h.includes("onfocus=\"hydrateTikTokCatalogOptions(this)\""), 'catalog dropdown options must be hydrated only on demand to reduce initial DOM');
