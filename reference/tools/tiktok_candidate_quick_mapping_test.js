assert(h.includes('chooseTikTokProductCandidate(${esc(JSON.stringify(String(key)))},${esc(JSON.stringify(String(c.key||\'\')))})'), 'candidate buttons must call a safe direct selection handler');
const start = h.indexOf('function chooseTikTokProductCandidate(');
const end = h.indexOf('\nfunction setTikTokLabelAssignee', start);
assert(start >= 0 && end > start, 'direct candidate choice handler missing');
const fn = h.slice(start, end);
assert(fn.includes('expectedPlantsPerSoldUnit'), 'candidate map must preserve total plants per sold unit');
assert(fn.includes("autoMatched:false"), 'manual choice must be recorded as Admin-confirmed');
assert(fn.includes('saveTikTokRecognitionRuleForProduct'), 'manual choice must be eligible to save a learned recognition rule');
assert(fn.includes('renderTikTokProductMappings();renderTikTokLabelQueue()'), 'mapping UI must update locally without full cloud render');
