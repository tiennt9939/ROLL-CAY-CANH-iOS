const addFn=h.slice(addStart,addEnd);
assert(addFn.includes('renderTikTokProductMappings();renderTikTokLabelQueue()'), 'add-map action must render locally and immediately');
assert(!addFn.includes('renderTikTokLabelImport(false)'), 'add-map action must not block on full cloud refresh');
